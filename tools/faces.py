#!/usr/bin/env python3
"""Crop the defender photos to round faces and embed them in src/05-faces.js.

Needs Pillow. Each entry: photo name -> (centre x, centre y, radius) in source pixels.
"""
import base64
import io
import os

from PIL import Image, ImageDraw

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
CROPS = {
    'kenny': (300, 330, 235),
    'dzakes': (265, 345, 225),
    'mates': (225, 285, 200),
    'kouc': (148, 135, 88),
    'vojta': (245, 290, 175),
}
SIZE = 256


def face(name, cx, cy, r):
    im = Image.open(os.path.join(ROOT, 'assets', 'photos', name + '.png')).convert('RGB')
    im = im.crop((cx - r, cy - r, cx + r, cy + r)).resize((SIZE, SIZE), Image.LANCZOS)
    mask = Image.new('L', (SIZE * 4, SIZE * 4), 0)
    ImageDraw.Draw(mask).ellipse((0, 0, SIZE * 4 - 1, SIZE * 4 - 1), fill=255)
    out = Image.new('RGBA', (SIZE, SIZE))
    out.paste(im, (0, 0), mask.resize((SIZE, SIZE), Image.LANCZOS))
    os.makedirs(os.path.join(ROOT, 'assets', 'faces'), exist_ok=True)
    out.save(os.path.join(ROOT, 'assets', 'faces', name + '.png'))
    buf = io.BytesIO()
    out.save(buf, 'PNG', optimize=True)
    return 'data:image/png;base64,' + base64.b64encode(buf.getvalue()).decode()


def main():
    lines = ['// Generated by tools/faces.py. Do not edit.', 'const FACE_SRC = {']
    for name, (cx, cy, r) in CROPS.items():
        lines.append("  %s: '%s'," % (name, face(name, cx, cy, r)))
    lines.append('};')
    with open(os.path.join(ROOT, 'src', '05-faces.js'), 'w') as f:
        f.write('\n'.join(lines) + '\n')
    print('wrote src/05-faces.js')


if __name__ == '__main__':
    main()
